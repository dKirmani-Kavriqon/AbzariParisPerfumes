/*
 * Cloudflare Worker entry (wrangler.jsonc "main"). Wraps the handler OpenNext generates:
 *
 * - /api/* and /media/* go straight to the API router, skipping Next.js (much less CPU per request).
 * - /admin pages are only served to an authenticated admin; everyone else gets the normal 404 page,
 *   so the admin's existence is not advertised. The admin API checks access again on every call.
 * - /product/<slug> is checked against the live published catalogue: products archived after the
 *   last build get the 404 page, and products added since the build are rendered from the live
 *   catalogue by the pre-built /product-view page. No product page is ever rendered on demand.
 * - Everything else is handled by Next.js as before.
 */
// @ts-expect-error .open-next/worker.js is generated by `opennextjs-cloudflare build`
import nextWorker from './.open-next/worker.js'
import { defaultDeps, type WorkerBindings } from './src/server/api/deps'
import { api } from './src/server/api/routes'
import { requireAdmin } from './src/server/auth/admin'
import { getServerEnv } from './src/server/env'
import { getPublishedCatalog } from './src/server/catalog/publish'
import { createLogger } from './src/server/log'
import { securityHeaders } from './src/config/security-headers'
// Written by scripts/build/not-found-page.ts after the OpenNext build.
import notFoundHtml from './.open-next/not-found.html'

type Ctx = { waitUntil(p: Promise<unknown>): void; passThroughOnException(): void }
type NextHandler = { fetch(request: Request, env: WorkerBindings, ctx: Ctx): Promise<Response> }

export default {
  async fetch(request: Request, env: WorkerBindings, ctx: Ctx): Promise<Response> {
    const url = new URL(request.url)
    const path = url.pathname

    if (path.startsWith('/api/') || path.startsWith('/media/')) return api().handle(request, defaultDeps(env))

    const product = /^\/product\/([a-z0-9]+(?:-[a-z0-9]+)*)\/?$/.exec(path)
    if (product) {
      const deps = defaultDeps(env)
      const published = await getPublishedCatalog({ ...deps, log: createLogger({ path }) }).catch(() => null)
      if (published) {
        if (!published.catalog.products.some((p) => p.slug === product[1])) return notFoundPage()
        const res = await (nextWorker as NextHandler).fetch(request, env, ctx)
        if (res.status !== 404) return res
        // Live in the catalogue but newer than this build: the live product page, at this address.
        const shell = await (nextWorker as NextHandler).fetch(new Request(new URL('/product-view', url), { headers: request.headers }), env, ctx)
        return new Response(shell.body, { status: shell.status, headers: shell.headers })
      }
      // Catalogue unavailable: fall through to the pre-built pages rather than failing.
    }

    if (path === '/admin' || path.startsWith('/admin/')) {
      try {
        await requireAdmin(request, getServerEnv())
      } catch {
        return notFoundPage()
      }
    }

    return (nextWorker as NextHandler).fetch(request, env, ctx)
  },
}

/** The site's own pre-rendered 404 page, served without running Next.js (about 1 ms of CPU). */
function notFoundPage() {
  const headers = new Headers({
    'content-type': 'text/html; charset=utf-8',
    'cache-control': 'private, no-cache, no-store, max-age=0, must-revalidate',
  })
  for (const { key, value } of securityHeaders) headers.set(key, value)
  return new Response(notFoundHtml, { status: 404, headers })
}
